export interface Link {
  label: string;
  href: string;
}

export interface Social {
  name: string;
  url: string;
}

export interface ProfileConfig {
  name: string;
  role: string;
  location: string;
  email: string;
  website: string;
  resume: string;
  avatar: string;
  socials: Social[];
}

export interface NavigationConfig {
  brand: {
    name: string;
    role: string;
    href: string;
  };
  navLinks: Link[];
  searchShortcut: string;
  primaryCta: Link;
}

export interface IdentityItem {
  id: number;
  label: string;
  /** Name of a hairline figure from identity-figures.js, or `stack` for the inline server sketch. */
  figure: string;
}

export interface HeroStat {
  value: string;
  label: string;
  href: string;
}

export interface HeroConfig {
  status: string;
  identities: IdentityItem[];
  portrait: {
    src: string;
    alt: string;
  };
  introduction: string;
  cta: Link;
  secondaryCta: Link;
  stats: HeroStat[];
}

export interface Migration {
  from: string;
  to: string;
  note: string;
}

export interface Role {
  company: string;
  client: string;
  title: string;
  period: string;
  metric: string;
  metricLabel: string;
  summary: string;
  highlights: string[];
  tags: string[];
}

export interface WorkConfig {
  heading: string;
  highlight: string;
  yearsExperience: string;
  experienceDomain: string;
  roles: Role[];
  migrationsTitle: string;
  migrations: Migration[];
  education: {
    school: string;
    degree: string;
    period: string;
  };
}

export interface EcosystemApp {
  id: string;
  name: string;
  tagline: string;
  description: string;
  stack: string[];
  href: string;
}

export interface Library {
  name: string;
  kind: string;
  description: string;
  install: string;
  stack: string[];
  href: string;
}

/** A package published to a registry (npm or Maven Central). */
export interface PublishedPackage {
  name: string;
  version: string;
  description: string;
  href: string;
}

export interface OpenSourceConfig {
  heading: string;
  highlight: string;
  intro: string;
  githubLink: Link;
  hub: EcosystemApp;
  satellites: EcosystemApp[];
  librariesTitle: string;
  libraries: Library[];
  npmTitle: string;
  npm: PublishedPackage[];
  npmProfile: Link;
  mavenTitle: string;
  maven: PublishedPackage[];
  mavenProfile: Link;
}

export interface SkillGroup {
  label: string;
  items: string[];
}

export interface Certification {
  name: string;
  issuer: string;
  valid: string;
}

export interface TerminalCommand {
  command: string;
  description: string;
  output: string[];
}

export interface StackConfig {
  heading: string;
  highlight: string;
  intro: string;
  groups: SkillGroup[];
  terminal: {
    prompt: string;
    greeting: string[];
    commands: TerminalCommand[];
  };
  certificationsTitle: string;
  certifications: Certification[];
}

export interface FooterColumn {
  title: string;
  links: Link[];
}

export interface FooterConfig {
  heading: string;
  highlight: string;
  intro: string;
  cta: Link;
  secondaryCta: Link;
  socials: Social[];
  copyright: string;
  tagline: string;
  columns: FooterColumn[];
}

export interface SearchItem {
  category: string;
  title: string;
  description: string;
  href: string;
  keywords: string;
}

/** One entry of public/blog/index.json, generated by scripts/build-blog.mjs. */
export interface BlogPostMeta {
  slug: string;
  title: string;
  description: string;
  date: string;
  updated?: string;
  tags: string[];
  cover?: string;
  /** PNG/JPG for link previews when the cover is an SVG. */
  ogImage?: string;
  coverAlt: string;
  featured: boolean;
  draft: boolean;
  readingMinutes: number;
}

export interface BlogStats {
  views: number;
  likes: number;
  /** Optional until the stats API reports them; absent means "unknown", not zero. */
  shares?: number;
  comments?: number;
  configured: boolean;
}

export type ShareChannel = 'copy' | 'linkedin' | 'x' | 'native';

export interface BlogComment {
  id: string;
  name: string;
  body: string;
  /** ISO 8601 timestamp. */
  createdAt: string;
}

export interface BlogCommentPage {
  comments: BlogComment[];
}

export interface PostedComment {
  comment: BlogComment;
  /** "pending" means it is held for moderation and not shown to everyone yet. */
  status: 'published' | 'pending';
}
